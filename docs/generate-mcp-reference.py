#!/usr/bin/env python3
"""Writes docs/mcp-tools.md from the tools OpenJersey's MCP server really lists,
so the reference cannot drift from the code.

    python3 docs/generate-mcp-reference.py

Needs the binary (OPENJERSEY or target/release/openjersey). `tools/list` is
answered by the bridge itself, so no window opens.
"""

import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "examples"))
from mcp_client import Mcp  # noqa: E402

HERE = Path(__file__).resolve().parent
EXE = os.environ.get("OPENJERSEY") or str(HERE.parent / "target" / "release" / "openjersey")

SECTIONS = [
    ("Look at the design", ["get_overview", "list_objects", "get_object", "list_garments", "list_presets", "render_preview"]),
    ("Add things", ["add_text", "add_placeholder", "add_rectangle", "add_ellipse", "add_preset_shape", "add_shape", "add_pattern", "import_image"]),
    ("Change things", ["update_object", "delete_object", "duplicate_object", "reorder_object", "group_objects", "ungroup", "centre_on_piece", "mirror_to_other_side", "select"]),
    ("Colours and garments", ["set_piece_color", "set_garments", "set_garment", "load_preset"]),
    ("Files", ["new_design", "open_design", "save_design", "export_print_template"]),
    ("Workflow", ["batch", "undo", "redo"]),
]


def type_of(schema: dict) -> str:
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"][:14]) + (" …" if len(schema["enum"]) > 14 else "")
    kind = schema.get("type", "any")
    if kind == "array":
        return f"list of {type_of(schema.get('items', {}))}"
    return kind


def main():
    mcp = Mcp(EXE, dict(os.environ))
    tools = {t["name"]: t for t in mcp.request("tools/list")["tools"]}
    instructions = mcp.request("initialize", {"protocolVersion": "2025-06-18", "capabilities": {}, "clientInfo": {"name": "docs", "version": "1"}}).get("instructions", "")
    prompts = mcp.request("prompts/list")["prompts"]
    mcp.close()

    listed = [name for _, names in SECTIONS for name in names]
    missing = sorted(set(tools) - set(listed))
    assert not missing, f"tools not placed in a section: {missing}"
    out = ["# MCP tool reference", "", "<!-- Generated by docs/generate-mcp-reference.py from the running server; do not edit by hand. -->", "",
           f"OpenJersey offers {len(tools)} tools over [MCP](https://modelcontextprotocol.io). See [Working with AI assistants](ai-assistants.md) for how to connect a client and what a session looks like.", "",
           "Positions are millimetres on the print sheet (x right, y down) unless a garment position is given: `panel` (`front` or `back`), `across_mm` (from the centre line, positive towards the wearer's left) and `above_hem_mm`. Colours are `#rrggbb`.", ""]
    for title, names in SECTIONS:
        out += [f"## {title}", ""]
        for name in names:
            tool = tools[name]
            flags = [label for key, label in (("readOnlyHint", "read-only"), ("destructiveHint", "can delete or overwrite")) if tool["annotations"].get(key)]
            out += [f"### `{name}`", "", tool["description"], ""]
            if flags:
                out += [f"*{', '.join(flags)}*", ""]
            props = tool["inputSchema"].get("properties", {})
            required = set(tool["inputSchema"].get("required", []))
            if props:
                out += ["| Parameter | Type | |", "| --- | --- | --- |"]
                for pname, schema in props.items():
                    note = schema.get("description", "").replace("|", "\\|")
                    out.append(f"| `{pname}` | {type_of(schema)} | {'required' + (' · ' + note if note else '') if pname in required else note} |")
                out.append("")
    out += ["## Prompts", "", "Clients that list MCP prompts offer these as starting points.", ""]
    for p in prompts:
        args = ", ".join(f"`{a['name']}`{' (required)' if a.get('required') else ''}" for a in p["arguments"]) or "none"
        out += [f"- **`{p['name']}`**: {p['description']} Arguments: {args}."]
    out += ["", "## Instructions the server sends to clients", "", "> " + instructions.replace("\n", "\n> "), ""]
    (HERE / "mcp-tools.md").write_text("\n".join(out))
    print(f"mcp-tools.md: {len(tools)} tools")


if __name__ == "__main__":
    main()
